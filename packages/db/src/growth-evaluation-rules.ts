// W4 outcome evaluation rules (pure, no database, no clock): given the
// initiative, its goal's immutable metric definition, the latest measurement
// plan, the W3 resolved series for each planned window and the recorded
// ledger, describe what was observed and whether the two windows can be set
// side by side. Descriptive only: no lift, attribution, ROI or success label.
import type {
  GrowthEvaluationAction, GrowthEvaluationCaveat, GrowthEvaluationComparison, GrowthEvaluationFinding, GrowthEvaluationReason,
  GrowthEvaluationWindow, GrowthEvent, GrowthGoal, GrowthOutcomeEvaluation, GrowthPlanRead, GrowthSeries, GrowthStatus,
} from "@openrecord/contracts"
import { GROWTH_EVALUATION_CAVEATS, GROWTH_EVALUATION_REASONS } from "@openrecord/contracts"

export type GrowthEvaluationActionRow = Omit<GrowthEvaluationAction, "performedDay" | "phase">
export interface GrowthEvaluationInput {
  readonly businessId: string
  readonly asOf: string
  readonly opportunity: {
    readonly id: string; readonly title: string; readonly goalId: string; readonly status: GrowthStatus
    readonly revision: number; readonly events: ReadonlyArray<GrowthEvent>
  }
  readonly goal: GrowthGoal
  readonly plan: GrowthPlanRead | null
  readonly planDeclarations: number
  /** W3 series read for exactly the plan's baseline and observation windows. */
  readonly baseline: GrowthSeries | null
  readonly observation: GrowthSeries | null
  readonly actions: ReadonlyArray<GrowthEvaluationActionRow>
  readonly actionsTruncated: boolean
  /** Other definitions of this business holding imports that overlap the planned period. */
  readonly excludedDefinitions: ReadonlyArray<{ readonly id: string; readonly version: number; readonly label: string }>
}

const isoDay = /^\d{4}-\d{2}-\d{2}$/
const dayMs = (day: string) => Date.parse(`${day}T00:00:00Z`)
const realDay = (day: string) => isoDay.test(day) && !Number.isNaN(dayMs(day)) && new Date(dayMs(day)).toISOString().slice(0, 10) === day
/** Inclusive calendar-day count. */
export const daysInclusive = (start: string, end: string): number => Math.round((dayMs(end) - dayMs(start)) / 86_400_000) + 1
/** The calendar day an instant falls on in an IANA time zone. */
export const localDay = (instant: string, timeZone: string): string => {
  const parts = new Intl.DateTimeFormat("en-CA", { timeZone, year: "numeric", month: "2-digit", day: "2-digit" }).formatToParts(new Date(instant))
  const get = (type: string) => parts.find(p => p.type === type)?.value ?? ""
  return `${get("year")}-${get("month")}-${get("day")}`
}
const round = (value: number, places: number) => {
  const factor = 10 ** places
  return Math.round(value * factor) / factor
}

const summarize = (role: GrowthEvaluationWindow["role"], series: GrowthSeries): GrowthEvaluationWindow => {
  const missingDays: string[] = [], unavailableDays: string[] = [], conflictingDays: string[] = [], syntheticDays: string[] = []
  let validDays = 0, validTotal = 0
  for (const d of series.days) {
    if (d.status === "MISSING") missingDays.push(d.day)
    else if (d.status === "UNAVAILABLE") unavailableDays.push(d.day)
    else {
      if (d.status === "CONFLICT") conflictingDays.push(d.day)
      if (d.origin === "SYNTHETIC") syntheticDays.push(d.day)
      if (d.status === "OK" && d.origin === "REAL" && d.value !== null) { validDays += 1; validTotal += d.value }
    }
  }
  const days = series.days.length
  return {
    role, start: series.start, end: series.end, days, validDays, coverage: days === 0 ? 0 : round(validDays / days, 4),
    missingDays, unavailableDays, conflictingDays, syntheticDays, validTotal,
    dailyMean: validDays === 0 ? null : { total: validTotal, days: validDays, value: round(validTotal / validDays, 2) },
    series: series.days, conflicts: series.conflicts,
  }
}

export const GROWTH_EVALUATION_LIMITATIONS: ReadonlyArray<string> = [
  "This is a descriptive before/after reading. It does not estimate incremental growth, causal lift, marketing-attributed conversions, revenue generated by an action, or return on marketing investment.",
  "A difference between the windows can come from seasonality, weekday mix, pricing, other channels, outside events or chance; none of these are controlled.",
  "COMPARABLE describes measurement quality only. It is not a success, failure or effectiveness judgement.",
  "Imported values are operator-supplied exports. OpenRecord does not authenticate the analytics platform or booking system that produced them.",
  "Operator-attested actions are what an operator asserted; they are not independently verified.",
]

/** Deterministic: the same input always yields the same evaluation. */
export const evaluateGrowthOutcome = (input: GrowthEvaluationInput): GrowthOutcomeEvaluation => {
  const reasons: Array<GrowthEvaluationFinding<GrowthEvaluationReason>> = []
  const caveats: Array<GrowthEvaluationFinding<GrowthEvaluationCaveat>> = []
  const block = (code: GrowthEvaluationReason, detail: string, refs: ReadonlyArray<string> = []) => { reasons.push({ code, detail, refs }) }
  const note = (code: GrowthEvaluationCaveat, detail: string, refs: ReadonlyArray<string> = []) => { caveats.push({ code, detail, refs }) }
  const { opportunity, goal, plan } = input
  const def = goal.metricDefinition
  const timeZone = def.reportingTimeZone

  const approval = opportunity.events.find(e => e.status === "APPROVED") ?? null
  if (!approval) block("INITIATIVE_NOT_APPROVED", `The initiative is ${opportunity.status.toLowerCase()} and has no human approval in its decision history.`)
  if (opportunity.status === "CANCELLED") note("INITIATIVE_CANCELLED", "The initiative was cancelled after approval; its recorded actions and measurements are still shown.")
  const currency = def.countingSemantics !== "EVENT_COUNT" || def.unit !== "COUNT" || def.currency !== null
  if (currency) block("CURRENCY_AGGREGATION_UNSUPPORTED", `${def.label} is a ${def.countingSemantics}/${def.unit} metric. Currency aggregation is not implemented, so no values are read or compared.`)

  // Windows are taken only from the declared plan, never inferred from data.
  let windows: { baselineStart: string; baselineEnd: string; observationStart: string; observationEnd: string } | null = null
  if (!plan) block("NO_MEASUREMENT_PLAN", "No measurement plan has been declared, so there are no baseline or observation windows to read.")
  else {
    const p = plan.plan
    if (p.metricDefinition.id !== def.id || p.metricDefinition.version !== def.version) {
      block("METRIC_DEFINITION_MISMATCH", `The plan is bound to metric definition version ${p.metricDefinition.version}, but the goal declares version ${def.version}. Values from different definitions are never mixed.`)
    }
    const valid = [p.baselineStart, p.baselineEnd, p.observationStart, p.observationEnd].every(realDay)
      && p.baselineStart <= p.baselineEnd && p.baselineEnd < p.observationStart && p.observationStart <= p.observationEnd
    if (!valid) block("INVALID_WINDOWS", "The plan's windows are not ordered calendar days (baseline must end before observation starts).")
    else windows = { baselineStart: p.baselineStart, baselineEnd: p.baselineEnd, observationStart: p.observationStart, observationEnd: p.observationEnd }
    if (plan.timing === "DECLARED_AFTER_EXECUTION") {
      block("PLAN_DECLARED_AFTER_EXECUTION", `The plan was declared ${p.declaredAt}, after a linked action was performed (${plan.firstLinkedExecutionAt ?? "unknown"}). Windows chosen after the fact cannot be read as pre-declared.`)
    }
    if (input.planDeclarations > 1) note("PLAN_REDECLARED", `${input.planDeclarations} plans were declared for this initiative; the latest is read and earlier ones stay on record.`)
    if (windows) {
      const today = localDay(input.asOf, timeZone)
      if (windows.observationEnd >= today) {
        block("OBSERVATION_INCOMPLETE", `The observation window ends ${windows.observationEnd}; in ${timeZone} it is ${today}, so the window is not complete.`)
      }
    }
  }

  // A series is used only when it is exactly the plan's window for the goal's definition.
  const bound = (series: GrowthSeries | null, start: string, end: string) => series !== null
    && series.metricDefinitionId === def.id && series.definitionVersion === def.version && series.timeZone === timeZone
    && series.start === start && series.end === end && series.days.length === daysInclusive(start, end)
  let baseline: GrowthEvaluationWindow | null = null, observation: GrowthEvaluationWindow | null = null
  if (windows && !currency) {
    const okBaseline = bound(input.baseline, windows.baselineStart, windows.baselineEnd)
    const okObservation = bound(input.observation, windows.observationStart, windows.observationEnd)
    if (!input.baseline || !input.observation) block("UNAVAILABLE_DAYS", "No measured series was read for a planned window.")
    else if (!okBaseline || !okObservation) {
      block("METRIC_DEFINITION_MISMATCH", "A measured series does not match the goal's exact metric definition, time zone and planned window; it was not used.")
    }
    if (okBaseline) baseline = summarize("BASELINE", input.baseline!)
    if (okObservation) observation = summarize("OBSERVATION", input.observation!)
    const both = [baseline, observation].filter((w): w is GrowthEvaluationWindow => w !== null)
    const gap = (pick: (w: GrowthEvaluationWindow) => ReadonlyArray<string>, code: GrowthEvaluationReason, what: string) => {
      const refs = both.flatMap(pick)
      if (refs.length) block(code, `${both.map(w => `${w.role.toLowerCase()}: ${pick(w).length}`).join(", ")} day(s) ${what}.`, refs)
    }
    gap(w => w.missingDays, "MISSING_DAYS", "were covered by an import that reported no value; missing is not zero")
    gap(w => w.unavailableDays, "UNAVAILABLE_DAYS", "are outside every import's declared range")
    gap(w => w.conflictingDays, "CONFLICTING_DAYS", "have imports that disagree on the value")
    gap(w => w.syntheticDays, "SYNTHETIC_DAYS", "carry synthetic fixture data, which is never treated as observed")
  }

  const phaseOf = (day: string): GrowthEvaluationAction["phase"] => {
    if (!windows) return "UNPLANNED"
    if (day < windows.baselineStart) return "BEFORE_BASELINE"
    if (day <= windows.baselineEnd) return "BASELINE"
    if (day < windows.observationStart) return "BETWEEN_WINDOWS"
    if (day <= windows.observationEnd) return "OBSERVATION"
    return "AFTER_OBSERVATION"
  }
  const actions: GrowthEvaluationAction[] = input.actions.map(a => {
    const performedDay = localDay(a.performedAt, timeZone)
    return { ...a, performedDay, phase: phaseOf(performedDay) }
  })
  const own = actions.filter(a => a.association === "THIS_INITIATIVE")
  if (own.length === 0) block("NO_RECORDED_EXECUTION", "No action is recorded for this initiative, so there is no execution to place between the windows.")
  if (windows) {
    // The action must fall after the baseline and no later than the first
    // observed day; otherwise one window mixes before and after.
    const outside = own.filter(a => !(a.performedDay > windows.baselineEnd && a.performedDay <= windows.observationStart))
    if (outside.length) {
      block("EXECUTION_TIMING_INCOMPATIBLE", `${outside.length} of this initiative's actions were performed outside the gap between baseline end (${windows.baselineEnd}) and observation start (${windows.observationStart}), so a window contains both before and after days.`, outside.map(a => a.id))
    }
    const onStart = own.filter(a => a.performedDay === windows.observationStart)
    if (onStart.length) note("EXECUTION_ON_OBSERVATION_START", `An action was performed on ${windows.observationStart}, the first observed day; part of that day precedes it.`, onStart.map(a => a.id))
  }
  if (own.length > 1) note("MULTIPLE_INITIATIVE_ACTIONS", `${own.length} actions are recorded for this initiative; the windows describe them together, not individually.`, own.map(a => a.id))
  const attested = own.filter(a => a.assurance === "OPERATOR_ATTESTED")
  if (attested.length) note("OPERATOR_ATTESTED_ONLY", `${attested.length} of ${own.length} of this initiative's actions are operator-attested and not independently verified.`, attested.map(a => a.id))
  const unspecified = actions.filter(a => a.assurance === "UNSPECIFIED")
  if (unspecified.length) note("UNSPECIFIED_ASSURANCE", `${unspecified.length} recorded action(s) predate assurance levels and carry no stated proof.`, unspecified.map(a => a.id))
  const others = actions.filter(a => a.association !== "THIS_INITIATIVE")
  if (others.length) {
    note("OTHER_ACTIONS_IN_PERIOD", `${others.length} other recorded action(s) fall inside the planned period. Any difference cannot be associated with this initiative alone.`, others.map(a => a.id))
  }
  if (input.actionsTruncated) note("ACTIONS_TRUNCATED", "More actions were recorded in the period than are listed; the list is incomplete.")
  if (input.excludedDefinitions.length) {
    note("OTHER_METRIC_VERSIONS_EXCLUDED", `Imports for ${input.excludedDefinitions.map(d => `${d.label} v${d.version}`).join(", ")} overlap the period and were excluded; only version ${def.version} is read.`, input.excludedDefinitions.map(d => d.id))
  }

  const status = reasons.length ? "INDETERMINATE" : "COMPARABLE"
  let comparison: GrowthEvaluationComparison | null = null
  if (status === "COMPARABLE" && baseline?.dailyMean && observation?.dailyMean) {
    const equal = baseline.days === observation.days
    if (!equal) note("UNEQUAL_WINDOW_LENGTHS", `The baseline has ${baseline.days} days and the observation ${observation.days}; totals are not compared, only per-day means.`)
    const before = baseline.validTotal / baseline.validDays, after = observation.validTotal / observation.validDays
    if (before === 0) note("ZERO_BASELINE", "The baseline per-day mean is zero, so no percentage change is defined.")
    comparison = {
      basis: equal ? "TOTAL_AND_DAILY_MEAN" : "DAILY_MEAN_ONLY",
      totalDifference: equal ? observation.validTotal - baseline.validTotal : null,
      dailyMeanDifference: round(after - before, 2),
      dailyMeanPercentChange: before === 0 ? null : round(((after - before) / before) * 100, 1),
    }
  }
  const order = <C extends string>(list: ReadonlyArray<C>) => (a: GrowthEvaluationFinding<C>, b: GrowthEvaluationFinding<C>) => list.indexOf(a.code) - list.indexOf(b.code)
  reasons.sort(order(GROWTH_EVALUATION_REASONS)); caveats.sort(order(GROWTH_EVALUATION_CAVEATS))

  return {
    businessId: input.businessId, opportunityId: opportunity.id, evaluatedAt: input.asOf, interpretation: "DESCRIPTIVE_ONLY", status,
    reasons, caveats,
    initiative: { id: opportunity.id, title: opportunity.title, status: opportunity.status, revision: opportunity.revision, approvedAt: approval?.createdAt ?? null, decisions: opportunity.events },
    goal: { id: goal.id, version: goal.version, statement: goal.statement },
    metric: {
      id: def.id, version: def.version, label: def.label, conversionKind: def.conversionKind, sourceKind: def.sourceKind, sourceIdentity: def.sourceIdentity,
      eventName: def.eventName, propertyRef: def.propertyRef, countingSemantics: def.countingSemantics, unit: def.unit, currency: def.currency, timeZone,
    },
    plan: plan ? {
      id: plan.plan.id, metricDefinitionId: plan.plan.metricDefinition.id, metricDefinitionVersion: plan.plan.metricDefinition.version,
      baselineStart: plan.plan.baselineStart, baselineEnd: plan.plan.baselineEnd, observationStart: plan.plan.observationStart, observationEnd: plan.plan.observationEnd,
      declaredAt: plan.plan.declaredAt, declaredByUserId: plan.plan.declaredByUserId, timing: plan.timing, firstLinkedExecutionAt: plan.firstLinkedExecutionAt,
      declarations: input.planDeclarations,
    } : null,
    baseline, observation, comparison, actions,
    assumptions: [
      `Daily values are ${def.label} (${def.countingSemantics}, ${def.unit}) from ${def.sourceIdentity}, metric version ${def.version}, bucketed by calendar day in ${timeZone}.`,
      "Each day's value comes from the newest import that reported that day; days no import reported stay absent and are never treated as zero.",
      "Action timing uses the operator-asserted performed time converted to the metric's time zone; the recorded time is shown but never used for windowing.",
      "Both windows come from the latest declared measurement plan; they are never inferred from the data.",
    ],
    limitations: GROWTH_EVALUATION_LIMITATIONS,
  }
}
